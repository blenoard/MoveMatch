"""Contract and implementation must agree: contracts/movematch.openapi.yaml  <->  the running FastAPI app.

Four checks:
1. Every operation marked `implemented` or `tested` exists in the app with the same status codes
   (and every operation of the app is in the contract).
2. The data shapes (properties and required fields) are the same in the contract and in the app.
3. Real responses of the app conform to the schemas of the contract.
4. All examples in the contract are valid against their schemas, and the error examples that come from the
   plan (data/error-examples.json) are identical to it.
"""
import json
from pathlib import Path

import pytest
import yaml
from fastapi.testclient import TestClient
from jsonschema import Draft202012Validator

from movematch.api import create_app

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = yaml.safe_load((ROOT / "contracts" / "movematch.openapi.yaml").read_text(encoding="utf-8"))
PLAN = json.loads((ROOT / "data" / "error-examples.json").read_text(encoding="utf-8"))
METHODS = ("get", "put", "post", "delete", "patch")
STATUSES = ("planned", "implemented", "tested")


@pytest.fixture
def client(tmp_path):
    with TestClient(create_app(tmp_path / "movematch.json")) as api:
        yield api


@pytest.fixture(scope="module")
def app_spec(tmp_path_factory) -> dict:
    """The OpenAPI document generated by the app (on a temporary data file)."""
    return create_app(tmp_path_factory.mktemp("spec") / "movematch.json").openapi()


def contract_operations() -> dict:
    return {(path, method): op for path, item in CONTRACT["paths"].items()
            for method, op in item.items() if method in METHODS}


def validator(schema_name: str) -> Draft202012Validator:
    """A validator for a schema of the contract (the components are embedded so that $ref works)."""
    schema = {**CONTRACT["components"]["schemas"][schema_name], "components": CONTRACT["components"]}
    return Draft202012Validator(schema)


def resolve(node: dict, kind: str) -> dict:
    """Follow a $ref like '#/components/examples/Name'."""
    if "$ref" in node:
        _, _, section, name = node["$ref"].split("/")
        assert section == kind
        return CONTRACT["components"][section][name]
    return node


# ----- 1. operations --------------------------------------------------------------------------------
def test_every_operation_has_a_valid_status_and_an_id():
    operations = contract_operations()
    assert len(operations) == 11
    ids = [op["operationId"] for op in operations.values()]
    assert len(ids) == len(set(ids))
    for op in operations.values():
        assert op["x-implementation-status"] in STATUSES


def test_implemented_operations_match_the_app(app_spec):
    app_paths = app_spec["paths"]
    app_ops = {(path, method): {code for code in op["responses"]}
               for path, item in app_paths.items() for method, op in item.items() if method in METHODS}
    contract_ops = {key: {code for code in op["responses"]}
                    for key, op in contract_operations().items()
                    if op["x-implementation-status"] in ("implemented", "tested")}
    assert contract_ops == app_ops  # same operations, same status codes, nothing missing on either side


def test_operation_ids_match_the_app(app_spec):
    app_paths = app_spec["paths"]
    app_ids = {(path, method): op["operationId"]
               for path, item in app_paths.items() for method, op in item.items() if method in METHODS}
    for key, op in contract_operations().items():
        if op["x-implementation-status"] != "planned":
            assert app_ids[key] == op["operationId"]


# ----- 2. data shapes ----------------------------------------------------------------------------------
@pytest.mark.parametrize("name", ["Address", "RequestItem", "MovingRequest", "OfferInput", "Offer", "Error"])
def test_schema_fields_match_the_app(app_spec, name):
    app_schema = app_spec["components"]["schemas"][name]
    contract_schema = CONTRACT["components"]["schemas"][name]
    assert set(contract_schema["properties"]) == set(app_schema["properties"])
    assert set(contract_schema["required"]) == set(app_schema.get("required", []))


# ----- 3. real responses conform to the contract ---------------------------------------------------------
def test_live_responses_conform_to_the_contract(client):
    for request in client.get("/moving-requests").json():
        validator("MovingRequest").validate(request)
    validator("MovingRequest").validate(client.get("/moving-requests/1042").json())

    created = client.post("/offers", json={"movingRequestId": 1047, "price": 800, "message": "Hello"},
                          headers={"X-Company-Id": "7"})
    assert created.status_code == 201
    validator("Offer").validate(created.json())
    validator("Offer").validate(client.get(created.headers["Location"]).json())
    validator("Offer").validate(client.get("/offers/305").json())

    errors = [
        client.get("/moving-requests/9999"),                                                      # 404
        client.get("/offers/0"),                                                                  # 422
        client.post("/offers", json={"movingRequestId": 1042, "price": 1750}, headers={"X-Company-Id": "7"}),  # 422
        client.post("/offers", json={"movingRequestId": 1042, "price": 1400}, headers={"X-Company-Id": "8"}),  # 409
        client.delete("/offers/305"),                                                             # 409
    ]
    assert [e.status_code for e in errors] == [404, 422, 422, 409, 409]
    for response in errors:
        validator("Error").validate(response.json())


def test_status_codes_of_live_responses_are_documented(client):
    ops = contract_operations()
    create = ops[("/offers", "post")]["responses"]
    assert "201" in create and "409" in create and "422" in create and "404" in create
    assert client.delete("/offers/309").status_code == 204 and "204" in ops[("/offers/{offer_id}", "delete")]["responses"]


def test_bad_id_example_is_the_real_message(client):
    example = CONTRACT["components"]["examples"]["ErrorBadId"]["value"]
    assert client.get("/offers/0").json() == example


# ----- 4. examples ---------------------------------------------------------------------------------------
def test_all_examples_in_the_contract_are_valid():
    checked = 0
    for (path, method), op in contract_operations().items():
        media = []
        if "requestBody" in op:
            media.append(op["requestBody"]["content"]["application/json"])
        media += [r["content"]["application/json"] for r in op["responses"].values() if "content" in r]
        for entry in media:
            schema_ref = entry["schema"]
            schema = {**schema_ref, "components": CONTRACT["components"]}
            for example in entry.get("examples", {}).values():
                Draft202012Validator(schema).validate(resolve(example, "examples")["value"])
                checked += 1
    assert checked >= 15


def test_planned_error_examples_equal_the_plan_in_data():
    """The contract and data/error-examples.json (the plan from Milestone 1) must say the same."""
    examples = CONTRACT["components"]["examples"]
    pairs = {
        "ErrorPriceOutOfRange": (4, "Offer price outside the allowed range"),
        "ErrorAlreadyOffered": (5, "Company already has an offer"),
        "ErrorNotAcceptingOffers": (6, "Request no longer accepts offers"),
        "ErrorAcceptedIsBinding": (9, "Withdraw an accepted offer"),
    }
    for name, (rule, case) in pairs.items():
        planned = next(e for e in PLAN if e["rule"] == rule and e["case"].startswith(case))
        assert examples[name]["value"] == planned["response"]
